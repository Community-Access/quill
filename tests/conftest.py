@pytest.fixture(autouse=True, scope="session")
def _never_write_to_the_real_profile() -> None:
    """Make the developer's own data directory read-only to the test suite.

    ``_DEV_BUILD`` plus ``QUILL_DATA_DIR`` isolates a test that remembers to
    ask for isolation. The failure mode is the test that *thinks* it did: patch
    ``quill.core.paths.app_data_dir`` and any module that did
    ``from quill.core.paths import app_data_dir`` still holds the original, so
    its writes land in the real profile with nothing to notice them.

    That is not hypothetical. A favorites test wrote its fixture stations --
    "Zeta", "Alpha", "Mu" -- straight into a developer's real
    ``radio_favorites.json``, replacing seven actual stations, and it went
    unnoticed for days because the suite passed every time.

    So the real directory is refused outright. Any write beneath it raises,
    naming the test that tried, which turns a silent data loss into a failure
    on the line that caused it.

    **Both profiles, since 2026-09-21.** The guard only ever covered QUILL's
    roaming profile, and QuillLite keeps its own under ``%LOCALAPPDATA%``. That
    gap had a cost with a number on it: ``quill.core.lite.recovery.new_slot``
    resolves the *real* recovery folder, and two tests in
    ``test_lite_save_path.py`` called it without isolation on every run, leaving
    a slot behind each time. Those slots were part of the sixty-nine unsaved
    documents a user was offered in one Yes/No on launch -- a test suite filling
    a developer's crash-recovery store, invisibly, for months.
    """
    import builtins
    import io
    import shutil
    import sys
    from pathlib import Path

    # The profile the *app* would use, computed the way app_data_dir computes
    # it -- deliberately not by calling app_data_dir(), which a test may have
    # already redirected.
    appdata = os.environ.get("APPDATA")
    if not appdata:
        yield
        return
    guarded = [(Path(appdata) / "Quill").resolve()]
    # QuillLite's own profile, which lives under LOCALAPPDATA rather than
    # APPDATA and was unguarded until 2026-09-21. Resolved the way
    # quill.core.lite.paths computes it, deliberately not by calling into that
    # module, which a test may already have redirected.
    local = os.environ.get("LOCALAPPDATA")
    if local:
        guarded.append((Path(local) / "QuillLite").resolve())
    original_open = builtins.open

    def _guarded_open(file, mode="r", *args, **kwargs):  # type: ignore[no-untyped-def]
        if any(flag in str(mode) for flag in ("w", "a", "x", "+")):
            try:
                target = Path(file).resolve()
            except (TypeError, ValueError, OSError):
                target = None
            if target is not None and any(target.is_relative_to(one) for one in guarded):
                raise AssertionError(
                    f"A test tried to write to a real profile: {target}. "
                    "Isolate it with the quill_data_dir fixture (or patch "
                    "app_data_dir / recovery_dir in *every* module that "
                    "imported the name), never the developer's own data."
                )
        return original_open(file, mode, *args, **kwargs)

    # Both names, and that is the second half of the 2026-09-21 fix.
    # ``builtins.open is io.open`` is the same object, but ``pathlib`` calls
    # ``io.open`` by attribute lookup on the module -- so patching only
    # ``builtins`` left every ``Path.write_text`` / ``write_bytes`` unguarded,
    # which is how ``write_json_atomic`` walked straight past this fixture.
    # Deleting is the other half, and it was never guarded at all. Writing is
    # what the fixture was written about, but a test that *removes* something
    # under a real profile loses data just as completely and leaves nothing
    # behind to notice -- there is no stray file afterwards to wonder about.
    #
    # It is guarded now because the recovery work of 2026-09-21 gave QUILL a
    # reason to delete: `begin_session` prunes autosave directories past the
    # keep window, so any test that builds a real MainFrame without isolating
    # its paths would take a month of a developer's crash-recovery snapshots
    # with it. That is a strictly worse failure than the one this fixture
    # already existed to prevent.
    original_rmtree = shutil.rmtree
    original_unlink = os.unlink
    original_remove = os.remove
    original_rmdir = os.rmdir
    original_path_unlink = Path.unlink

    def _refuse(target: object, verb: str) -> None:
        try:
            resolved = Path(target).resolve()  # type: ignore[arg-type]
        except (TypeError, ValueError, OSError):
            return
        if not any(resolved.is_relative_to(one) for one in guarded):
            return
        # Named on stderr *before* it is raised, because a refusal that is
        # caught tells nobody anything. Both leaks found on 2026-09-21 were
        # swallowed by a broad ``except Exception`` in the code under test --
        # the data was saved and the test still passed, so the guard protected
        # the profile and taught nothing about which test to fix. The line
        # below is the teaching half, and PYTEST_CURRENT_TEST is how it knows
        # whose fault it is.
        culprit = os.environ.get("PYTEST_CURRENT_TEST", "unknown test")
        message = (
            f"A test tried to {verb} a real profile: {resolved}. "
            "Isolate it with the quill_data_dir fixture (or patch "
            "app_data_dir / recovery_dir in *every* module that imported "
            "the name), never the developer's own data."
        )
        print(f"PROFILE GUARD: {culprit}: {message}", file=sys.stderr)
        raise AssertionError(message)

    def _guarded_rmtree(path, *args, **kwargs):  # type: ignore[no-untyped-def]
        _refuse(path, "delete a directory tree in")
        return original_rmtree(path, *args, **kwargs)

    def _guarded_unlink(path, *args, **kwargs):  # type: ignore[no-untyped-def]
        _refuse(path, "delete a file in")
        return original_unlink(path, *args, **kwargs)

    def _guarded_remove(path, *args, **kwargs):  # type: ignore[no-untyped-def]
        _refuse(path, "delete a file in")
        return original_remove(path, *args, **kwargs)

    def _guarded_rmdir(path, *args, **kwargs):  # type: ignore[no-untyped-def]
        _refuse(path, "remove a directory in")
        return original_rmdir(path, *args, **kwargs)

    def _guarded_path_unlink(self, *args, **kwargs):  # type: ignore[no-untyped-def]
        _refuse(self, "delete a file in")
        return original_path_unlink(self, *args, **kwargs)

    builtins.open = _guarded_open
    io.open = _guarded_open  # type: ignore[assignment]
    shutil.rmtree = _guarded_rmtree  # type: ignore[assignment]
    os.unlink = _guarded_unlink  # type: ignore[assignment]
    os.remove = _guarded_remove  # type: ignore[assignment]
    os.rmdir = _guarded_rmdir  # type: ignore[assignment]
    Path.unlink = _guarded_path_unlink  # type: ignore[assignment,method-assign]
    try:
        yield
    finally:
        builtins.open = original_open
        io.open = original_open  # type: ignore[assignment]
        shutil.rmtree = original_rmtree  # type: ignore[assignment]
        os.unlink = original_unlink  # type: ignore[assignment]
        os.remove = original_remove  # type: ignore[assignment]
        os.rmdir = original_rmdir  # type: ignore[assignment]
        Path.unlink = original_path_unlink  # type: ignore[assignment,method-assign]


#: Environment variables the leak guard ignores, and why. Everything else is a
#: leak and fails the test that caused it -- see :func:`_no_environment_leaks`.
#:
#: ``PYTEST_CURRENT_TEST`` is pytest's own bookkeeping and legitimately differs
#: between the setup and teardown phases the guard compares across.
#:
#: The other two are one-time *process* bootstrap performed by production code
#: rather than by a test. ``quill.core.spellcheck`` sets ``ENCHANT_CONFIG_DIR``
#: before the first Enchant broker is constructed -- the broker reads it at
#: construction, so it cannot be set afterwards -- and importing Enchant puts
#: its DLL directory on ``PATH``. Both are idempotent, both point inside the
#: isolated test profile, and undoing them would only make the next test that
#: spell-checks pay for the setup again.
_ENV_LEAK_ALLOWED = frozenset({"PYTEST_CURRENT_TEST", "ENCHANT_CONFIG_DIR", "PATH"})

#: Where the pre-test snapshot lives between the two hooks below.
_ENV_BEFORE: pytest.StashKey[dict[str, str]] = pytest.StashKey()


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_protocol(item: pytest.Item, nextitem: pytest.Item | None):
    """Snapshot ``os.environ`` before a test runs. Paired with the teardown hook."""
    item.stash[_ENV_BEFORE] = dict(os.environ)
    yield


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_teardown(item: pytest.Item, nextitem: pytest.Item | None):
    """Fail a test that changes ``os.environ`` and does not change it back.

    The footgun this exists for: ``monkeypatch.delenv(name, raising=False)``
    records **nothing** when the variable is already absent, so there is no
    entry to undo. If the code under test then writes that variable directly --
    which several QUILL functions do, deliberately -- the write outlives the
    test and every later test in the same process sees it.

    It went unnoticed for as long as the tests existed and surfaced on
    2026-09-11 as four failures in ``tests/unit/core/test_paths.py`` that had
    nothing to do with paths: a leaked ``QUILL_APP_ROOT`` made ``app_data_dir``
    resolve a portable root. It only appeared then because an unrelated new test
    file changed ``--dist=loadfile``'s file-to-worker split and put the guilty
    file and the victim file on one worker. That is the signature of the whole
    class -- it presents as "CI is flaky on a machine I cannot reproduce", which
    is why it needs a gate rather than vigilance.

    **A teardown hookwrapper, not an autouse fixture**, and that is not a style
    choice. A fixture finalizer cannot be made to run reliably last: the obvious
    arrangement (declare it first, so it is set up first and finalized last) was
    tried and does not hold -- ``monkeypatch`` undoes its work *after* such a
    fixture, so every ordinary ``monkeypatch.setenv`` was reported as a leak.
    The after-yield half of this hook runs once every finalizer for the item has
    completed, which is the only point where the question can be asked honestly.
    """
    yield
    before = item.stash.get(_ENV_BEFORE, None)
    if before is None:  # pragma: no cover - defensive; protocol hook always runs
        return
    after = dict(os.environ)
    names = set(before) ^ set(after)
    names |= {name for name in set(before) & set(after) if before[name] != after[name]}
    leaked = sorted(names - _ENV_LEAK_ALLOWED)
    if not leaked:
        return
    detail = ", ".join(
        f"{name}: {before.get(name, '<unset>')!r} -> {after.get(name, '<unset>')!r}"
        for name in leaked
    )
    # Put it back, so one leak does not cascade into every later test on this
    # worker and bury its own cause under a screenful of unrelated failures.
    for name in leaked:
        if name in before:
            os.environ[name] = before[name]
        else:
            os.environ.pop(name, None)
    raise AssertionError(
        f"this test changed os.environ and left it changed: {detail}. "
        "If the code under test writes the variable itself, note that "
        "monkeypatch.delenv(name, raising=False) records nothing when the name "
        "is already absent -- use the absent_env fixture, which guarantees "
        "removal on teardown. If the change is deliberate process bootstrap, "
        "add the name to _ENV_LEAK_ALLOWED in tests/conftest.py with the reason."
    )


@pytest.fixture
def absent_env(monkeypatch: pytest.MonkeyPatch) -> Iterator[Callable[..., None]]:
    """``absent_env("GH_TOKEN", ...)``: gone for the test, and gone afterwards.

    What ``monkeypatch.delenv(name, raising=False)`` looks like it does. The
    difference matters only when the code under test writes the variable itself,
    and that is exactly when it matters most -- see :func:`_no_environment_leaks`.
    """
    removed: list[str] = []

    def hide(*names: str) -> None:
        for name in names:
            monkeypatch.delenv(name, raising=False)
            removed.append(name)

    yield hide
    for name in removed:
        os.environ.pop(name, None)


