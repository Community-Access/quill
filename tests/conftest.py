"""Root test configuration.

Activates the ``_DEV_BUILD`` flag in :mod:`quill.core.paths` for the entire
test suite so that ``QUILL_DATA_DIR`` overrides (used by almost every test
fixture for isolation) are honoured.  Without this flag the guard added by
H-1-core silently ignores ``QUILL_DATA_DIR`` in non-dev builds, causing tests
to write to the real ``%APPDATA%\\Quill`` path and fail with stale state.
"""

from __future__ import annotations

import os
from collections.abc import Callable, Iterator
from pathlib import Path

import pytest


def pytest_configure(config: pytest.Config) -> None:
    """Force pytest's ``tmp_path`` base directory under ``$HOME``.

    ``paths.app_data_dir()`` only honours a ``QUILL_DATA_DIR`` override when
    it resolves under ``Path.home()`` (H-1-core: rejects an override that
    could redirect to an attacker-controlled path). Nearly every test that
    isolates ``QUILL_DATA_DIR`` does so via the ``tmp_path`` fixture -- but
    pytest's default tmp base is the OS temp directory, which on Windows
    happens to live under ``%USERPROFILE%`` (home-relative) but on macOS is
    ``/private/var/folders/...`` -- never under ``$HOME``. Every such test on
    macOS therefore silently failed the H-1-core check and fell through to
    the *real* ``~/.quill`` directory, reading and writing real state and
    cross-contaminating later tests. This was invisible until now because
    the macOS release CI job always segfaulted before pytest could report
    the resulting failures (see the voice_browser_dialog fix). Forcing
    basetemp under ``$HOME`` makes ``tmp_path`` satisfy the guard -- and
    thus provide real isolation -- on every platform, not just by accident
    on Windows.
    """
    if config.option.basetemp is None:
        config.option.basetemp = str(_session_basetemp())
    _redirect_comtypes_gen_dir()
    _configure_hypothesis()


def _redirect_comtypes_gen_dir() -> None:
    """Give comtypes a cache of its own, outside the developer's profile.

    comtypes writes a generated Python wrapper to disk the first time it
    touches a COM type library -- SAPI's SpVoice, oleacc, and the Rich Edit
    TOM that the rich-text surface needs. QUILL points that cache at
    ``running_app_data_dir() / "comtypes_gen"``, which is the right answer for
    the shipped app and the wrong one for a test run: it is inside the real
    profile, which the guard below refuses to let the suite write to.

    On a developer's machine that never showed, because the wrappers were
    already generated by running the app, so nothing was written and nothing
    was refused. On a fresh CI runner there is no cache, comtypes tries to
    generate, the guard fires, and the error surfaces as
    ``RichEditRtfError: Could not reach the Rich Edit text object model`` --
    which reads like the runner has no Rich Edit and is nothing of the kind.
    GATE-RICH-ROUNDTRIP's thirteen tests failed that way on every CI run while
    passing locally every time, which is the worst shape a red build can have:
    one that only the machine nobody watches can see.

    So the redirect happens here, before collection and therefore before
    anything can touch COM, and ``_redirected`` is set so the app's own
    redirect leaves it alone. The last path component stays ``comtypes_gen``
    because :mod:`tests.unit.platform.windows.test_comtypes_setup` checks the
    name. Per worker rather than shared: two xdist workers generating the same
    wrapper into the same folder is a race, and regenerating a handful of type
    libraries once per worker costs a second.
    """
    try:
        import comtypes.client as cc  # type: ignore[import-untyped]
    except Exception:  # noqa: BLE001 - not Windows, or no comtypes; nothing to do
        return
    worker = os.environ.get("PYTEST_XDIST_WORKER") or f"p{os.getpid()}"
    gen_dir = Path.home() / ".quill-pytest-tmp" / f"comtypes-{worker}" / "comtypes_gen"
    try:
        gen_dir.mkdir(parents=True, exist_ok=True)
    except OSError:
        return  # comtypes falls back to in-memory codegen on its own
    cc.gen_dir = str(gen_dir)
    try:
        from quill.platform.windows import comtypes_setup

        comtypes_setup._redirected = True
    except Exception:  # noqa: BLE001 - the app module is not importable here
        pass


def _session_basetemp() -> Path:
    """A temp root under ``$HOME`` that is unique to this pytest session.

    The directory has to live under ``$HOME`` (see above), but it must *not* be
    shared between concurrent sessions. pytest clears its basetemp at startup,
    so two runs at once -- a full suite in one terminal and a focused subset in
    another, or a background run alongside a foreground one -- had the second
    run deleting the first run's live temp files. That surfaced as hundreds of
    unrelated PermissionError/OSError setup failures in whichever session lost
    the race, which is about as misleading as a test failure can be.

    Keying on the process id gives each session its own root. xdist workers are
    unaffected: the controller passes them an explicit basetemp, so this hook
    never runs for them and they keep sharing the controller's tree.

    The root is created here because pytest is not going to: for an explicitly
    given basetemp it calls ``basetemp.mkdir(mode=0o700)`` with no ``parents``,
    which succeeded while this returned a path one level under ``$HOME`` and
    fails with ``FileNotFoundError`` now that it returns a per-session
    subdirectory. It only ever showed up on a machine where the root did not
    already exist -- i.e. every fresh CI runner, and never a developer's second
    run.
    """
    root = Path.home() / ".quill-pytest-tmp"
    root.mkdir(parents=True, exist_ok=True)
    token = os.environ.get("QUILL_PYTEST_RUN_ID") or f"run-{os.getpid()}"
    _prune_stale_runs(root)
    return root / token


#: The one group every machine-global test shares, and therefore the one
#: worker they all run on.
MACHINE_GLOBAL_GROUP = "machine-global"


@pytest.hookimpl(tryfirst=True)
def pytest_collection_modifyitems(config: pytest.Config, items: list[pytest.Item]) -> None:
    """Make ``-n auto --dist loadgroup`` safe: serialize what cannot be shared.

    The suite parallelizes cleanly except where a test drives a resource the
    *machine* owns rather than the process -- the Windows clipboard, the
    system-wide ``RegisterHotKey`` table, the screen-reader COM bridges. Two
    workers using one of those at the same time is not slow, it is wrong: the
    clipboard read belongs to whoever wrote last, and a hotkey can only be
    registered once on the whole desktop. In 2026-08 a worker died outright
    around the clipboard-backed clip-library dialog tests, taking its queued
    tests with it.

    Mechanics: with ``--dist loadgroup`` xdist schedules by ``xdist_group``
    mark. Tests marked ``machine_global`` all get the one shared
    ``machine-global`` group and therefore one worker; every other test gets its
    *file* as its group, preserving loadfile's file-affinity for module-scoped
    fixtures while fanning out. Serial runs are unaffected -- the marks are
    inert without xdist.

    The fast path is therefore:  ``pytest -q -n 8 --dist loadgroup``

    **The two ways this was wrong before, so neither is rediscovered.**

    *It was marked up and had no effect* (2026-08 to 2026-09-10). xdist reads
    the mark in **its own** ``pytest_collection_modifyitems``
    (``xdist/remote.py`` rewrites each item's nodeid to ``<nodeid>@<group>`` and
    the scheduler splits on that suffix), so this hook has to run first -- and
    without ``tryfirst`` it did not. Measured on a full ``-n 8`` run: all eight
    workers were running ``tests/unit/ui`` tests. The only visible symptom was
    ``test_clip_library_dialog.py::test_copy_defaults_to_plain_text_format``
    reading an empty clipboard under ``-n 8`` and passing on its own -- which
    reads as a flaky test rather than as the scheduler ignoring the group.

    *Then it was too coarse to terminate.* Adding ``tryfirst`` while the group
    was "everything under ``tests/unit/ui``" made the grouping real and put all
    **3,606** wx tests on one worker, and the suite then ran every test and
    never exited: 17,821 of 17,823 results, zero failures, no summary, eight
    processes still alive. Concentrating that many wx/COM objects in one worker
    hangs its shutdown, so the controller waits for a ``workerfinished`` that
    never comes.

    **The middle path, taken 2026-09-10.** Neither extreme: a directory is not
    the unit, a *resource* is. The mark is applied per file by hand
    (``pytestmark = pytest.mark.machine_global``) to the files that actually
    touch one -- which turned out to be far fewer than the directory suggested,
    because most of ``tests/unit/ui`` mocks ``wx.TheClipboard`` rather than using
    it. A new test that reaches for one of these resources has to say so, which
    is a line of code and a decision somebody made, rather than a directory it
    happened to be filed under.

    **What this fixed, and what it did not.** It fixed the hang it was aimed at:
    with a small group the ``tryfirst`` ordering is safe and the suite prints a
    summary, where the all-of-``tests/unit/ui`` version never did. Measured
    2026-09-10 over three full runs: one clean (**18,054 passed, 0 failed,
    4:41**), and two in which a worker died with ``node down: Not properly
    terminated`` -- once completing anyway with that worker's queued test
    reported failed, once leaving the controller waiting at 99%.

    Those crashes are **not** what this hook is about and predate it: a run
    before this change died the same way, with an extra
    ``INTERNALERROR ... KeyError: <WorkerController gw8>`` from xdist's own
    scheduler. They are a native crash somewhere in the wx/UI tests, they are
    unrelated to the clipboard grouping, and nobody has chased them.

    So: ``-n 8 --dist loadgroup`` is the **fast** path, not the authoritative
    one. A failure it reports is worth re-running on its own before believing
    it -- every one seen so far passed serially. The plain ``pytest -q`` run is
    the answer that counts (**18,117 passed, 0 failed, 14:15**, same tree, same
    day).
    """
    for item in items:
        if item.get_closest_marker("xdist_group") is not None:
            continue
        if item.get_closest_marker("machine_global") is not None:
            item.add_marker(pytest.mark.xdist_group(MACHINE_GLOBAL_GROUP))
            continue
        item.add_marker(pytest.mark.xdist_group(str(item.fspath).replace("\\", "/")))


def _prune_stale_runs(root: Path, *, max_age_seconds: float = 6 * 60 * 60) -> None:
    """Delete run directories left behind by long-finished sessions.

    Best-effort and deliberately conservative: only directories older than
    *max_age_seconds* are considered, so a session still running (whose files
    are being touched continuously) is never a candidate, and every error is
    swallowed -- failing to tidy up must never fail a test run.
    """
    import shutil
    import time

    try:
        entries = list(root.iterdir())
    except OSError:
        return
    cutoff = time.time() - max_age_seconds
    for entry in entries:
        # Everything under this root is pytest's, including the flat
        # ``test_<name>0`` directories left by the previous shared-basetemp
        # layout, so age is the only thing worth checking.
        try:
            if entry.stat().st_mtime >= cutoff:
                continue
            if entry.is_dir():
                shutil.rmtree(entry, ignore_errors=True)
            else:
                entry.unlink(missing_ok=True)
        except OSError:
            continue


def _configure_hypothesis() -> None:
    """Register the suite's Hypothesis profile (no-op if it isn't installed).

    ``deadline=None`` disables Hypothesis's per-example time limit. The default
    (200ms) measures wall-clock per generated example, which on a loaded CI
    runner -- four xdist workers plus AST-scanning gates -- turns an otherwise
    passing property into an intermittent DeadlineExceeded. Correctness, not
    latency, is what these properties assert; the suite-wide pytest ``timeout``
    still bounds a genuinely hung test.
    """
    try:
        from hypothesis import HealthCheck, settings
    except ModuleNotFoundError:  # property tests skip themselves without it
        return
    settings.register_profile(
        "quill",
        deadline=None,
        suppress_health_check=[HealthCheck.too_slow],
    )
    settings.load_profile("quill")


