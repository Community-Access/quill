"""Bake Quill Radio's last.fm API key and shared secret into a build. Generates no secret.

Same shape as ``generate_podcast_index_key.py`` and
``generate_youtube_oauth_client.py``: an API account issued by last.fm to a
registered developer (https://www.last.fm/api/account/create) is moved from the
build environment into the gitignored ``quill/_lastfm_api_key.py`` module the
packager can see. Nothing here invents or derives the pair.

What the pair is for: scrobbling to last.fm and Libre.fm (``quill.core.radio.lastfm``).
It identifies the application only; each listener still signs in with their own
account in the browser, and can paste their own pair into Preferences, which
wins. A build with no pair still works -- signing in then asks the listener for
their own.

Usage::

    QUILL_LASTFM_API_KEY=<key> QUILL_LASTFM_SHARED_SECRET=<secret> \\
        python tools/generate_lastfm_api_key.py

Or point ``QUILL_LASTFM_API_KEY_FILE`` / ``QUILL_LASTFM_SHARED_SECRET_FILE`` at
files on disk. A run with nothing in the environment keeps a pair already
written rather than wiping it.
"""

from __future__ import annotations

import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_FILE = ROOT / "quill" / "_lastfm_api_key.py"

KEY_ENV = "QUILL_LASTFM_API_KEY"
SECRET_ENV = "QUILL_LASTFM_SHARED_SECRET"
KEY_FILE_ENV = "QUILL_LASTFM_API_KEY_FILE"
SECRET_FILE_ENV = "QUILL_LASTFM_SHARED_SECRET_FILE"


def write_module(key: str, secret: str, output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        "# This file is generated by tools/generate_lastfm_api_key.py. Do not edit by hand.\n"
        "\n"
        f"BUNDLED_LASTFM_API_KEY = {key!r}\n"
        f"BUNDLED_LASTFM_SHARED_SECRET = {secret!r}\n",
        encoding="utf-8",
        newline="\n",
    )


def read_existing(output_path: Path) -> tuple[str, str]:
    """The non-empty pair already written, or ``("", "")``."""
    if not output_path.is_file():
        return "", ""
    text = output_path.read_text("utf-8")

    def _find(name: str) -> str:
        match = re.search(rf"^{name} = (['\"])(.*)\1", text, re.MULTILINE)
        return match.group(2) if match else ""

    return _find("BUNDLED_LASTFM_API_KEY"), _find("BUNDLED_LASTFM_SHARED_SECRET")


def _from_env(value_env: str, file_env: str) -> str:
    """One value: the env var, else the file it names. No network, ever."""
    value = os.environ.get(value_env, "").strip()
    if value:
        return value
    named = os.environ.get(file_env, "").strip()
    if named:
        try:
            return Path(named).read_text(encoding="utf-8").strip()
        except OSError:
            return ""
    return ""


def resolve() -> tuple[str, str]:
    return _from_env(KEY_ENV, KEY_FILE_ENV), _from_env(SECRET_ENV, SECRET_FILE_ENV)


def main(argv: list[str] | None = None, *, output: Path = OUTPUT_FILE) -> int:
    key, secret = resolve()
    if not (key and secret):
        old_key, old_secret = read_existing(output)
        if old_key and old_secret:
            print(f"No last.fm API pair in env/file; keeping the one in {output}.")
            return 0
        key, secret = "", ""
    write_module(key, secret, output)
    if key:
        print(f"Wrote {output} with the bundled last.fm API pair.")
    else:
        print(
            f"No complete last.fm API pair found; wrote {output} empty. Signing in "
            "to last.fm will ask the listener for their own API key."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
