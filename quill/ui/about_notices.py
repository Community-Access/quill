"""Help > About, with the licences one button away, for every app in the family.

Each app's About used to be a message box: its name, version and support
address, and no way to reach the licences of what it ships. This is that box
as a small dialog -- the same text in a read-only field a screen reader can
read line by line, a **Licences and Notices** button, and Close -- so every
app answers "what is inside this, and under what terms?" the same way.

The button opens the plain-text notices the installer and the portable zip
put beside the program (``THIRD-PARTY-NOTICES.txt``, generated by
``quill/tools/build_third_party_notices.py``). The lookup mirrors
:mod:`quill.ui.whats_new`: the app's own folder first, then this checkout, then
the family document, so a dev run is not empty-handed either.

Only :func:`show_about_dialog` and :func:`show_app_about` touch wx, and import
it when called.
"""

from __future__ import annotations

import webbrowser
from collections.abc import Callable
from pathlib import Path
from typing import Any

__all__ = [
    "NOTICES_BUTTON_LABEL",
    "NOTICES_FILE",
    "find_notices",
    "notices_candidates",
    "open_notices",
    "quill_notices_text",
    "show_about_dialog",
    "show_app_about",
]

#: What the installers and portable zips put beside every program.
NOTICES_FILE = "THIRD-PARTY-NOTICES.txt"

#: The About button. L is free in every About window: the only other access
#: key there is the text field's D, and Close carries none (GATE-14).
NOTICES_BUTTON_LABEL = "&Licences and Notices"

_REPO_ROOT = Path(__file__).resolve().parents[2]
_LEGAL = _REPO_ROOT / "docs" / "legal"


def notices_candidates(app: str, *, folders: list[Path] | None = None) -> list[Path]:
    """Every place *app*'s notices may be, most specific first.

    *app* is the folder name under ``standalone/`` (``"radio"``), or
    ``"quill"`` for QUILL itself. *folders* overrides
    :func:`quill.core.app_folders.app_folders`, for tests.
    """
    if folders is None:
        from quill.core.app_folders import app_folders

        folders = app_folders()
    found = [folder / NOTICES_FILE for folder in folders]
    if app == "quill":
        found.append(_LEGAL / "THIRD-PARTY-NOTICES-QUILL.txt")
    else:
        found.append(_REPO_ROOT / "standalone" / app / NOTICES_FILE)
    # The family document lists every product, so an app without a file of
    # its own (Quill Media Player has no installer) still has an answer.
    found.append(_LEGAL / "THIRD_PARTY_NOTICES.txt")
    return found


def find_notices(app: str, *, folders: list[Path] | None = None) -> Path | None:
    """The first notices file that exists for *app*, or None."""
    for candidate in notices_candidates(app, folders=folders):
        try:
            if candidate.is_file():
                return candidate
        except OSError:
            continue
    return None


def open_notices(
    app: str,
    app_name: str,
    announce: Callable[[str], object],
    *,
    folders: list[Path] | None = None,
    open_url: Callable[[str], bool] = webbrowser.open,
) -> bool:
    """Open *app*'s notices in the system's text viewer; True when it opened.

    The outcome is spoken through *announce*: another window taking focus is
    the only other sign anything happened, and a stripped build without the
    file must say so rather than do nothing.
    """
    found = find_notices(app, folders=folders)
    if found is None:
        announce(f"The licences and notices for {app_name} were not found in this build.")
        return False
    if open_url(found.as_uri()):
        announce(f"Opened the licences and notices for {app_name}.")
        return True
    announce(f"The licences and notices for {app_name} are in {found}")
    return False


def quill_notices_text(project_root: Path, pyproject_path: Path) -> str:
    """What QUILL's Help > Open Third-Party Notices puts in a new tab.

    The generated file wins: beside ``quill.exe`` in a build, ``docs/legal`` in
    a checkout. Rendering from package metadata is the fallback, and a build
    has no ``pyproject.toml`` to render from, so it says so instead.
    """
    from quill.core import compliance
    from quill.core.app_folders import app_folders

    candidates = [folder / NOTICES_FILE for folder in app_folders()]
    candidates.append(project_root / "docs" / "legal" / "THIRD-PARTY-NOTICES-QUILL.txt")
    for candidate in candidates:
        if candidate.is_file():
            return candidate.read_text(encoding="utf-8")
    if not pyproject_path.exists():
        return "# Third-Party Notices\n\nDependency metadata is not available in this build.\n"
    return compliance.render_full_third_party_notices(pyproject_path, project_root)


def show_about_dialog(
    parent: Any,
    *,
    app: str,
    app_name: str,
    body: str,
    announce: Callable[[str], object],
    show_modal: Callable[[Any, str], int],
    on_ready: Callable[[Any], None] | None = None,
) -> None:
    """About *app_name*: *body* to read, Licences and Notices, and Close.

    *show_modal* is the caller's modal path (``host._show_modal_dialog`` in the
    app shells, ``dialog_contract.show_modal_dialog`` elsewhere), so the dialog
    joins that app's modal stack and region cues. *on_ready* is handed the text
    field before the window shows, for an About that adds to it later.
    """
    import wx

    from quill.ui.dialog_contract import (
        apply_modal_ids,
        bind_close_button,
        readable_min_size,
    )

    title = f"About {app_name}"
    dialog = wx.Dialog(parent, title=title, style=wx.DEFAULT_DIALOG_STYLE | wx.RESIZE_BORDER)
    root = wx.BoxSizer(wx.VERTICAL)
    label = wx.StaticText(dialog, label="&Details:")
    root.Add(label, 0, wx.LEFT | wx.RIGHT | wx.TOP, 12)
    field = wx.TextCtrl(
        dialog,
        value=body,
        style=wx.TE_MULTILINE | wx.TE_READONLY | wx.TE_RICH2,
        name="about_details",
    )
    field.SetHelpText(
        f"What {app_name} is, its version and where to get support. Read it with the arrow keys."
    )
    field.SetMinSize(readable_min_size(field, lines=10))
    root.Add(field, 1, wx.EXPAND | wx.ALL, 12)

    buttons = wx.BoxSizer(wx.HORIZONTAL)
    notices = wx.Button(dialog, label=NOTICES_BUTTON_LABEL, name="about_notices")
    notices.SetHelpText(
        f"Open the licences of {app_name} and of the third-party software, data and "
        "sounds it includes, as a text file."
    )
    notices.Bind(wx.EVT_BUTTON, lambda _e: open_notices(app, app_name, announce))
    close = wx.Button(dialog, wx.ID_CANCEL, "Close")
    close.SetHelpText("Close this window.")
    bind_close_button(dialog, close, modeless=False)
    buttons.Add(notices, 0, wx.RIGHT, 8)
    buttons.AddStretchSpacer()
    buttons.Add(close, 0)
    root.Add(buttons, 0, wx.EXPAND | wx.LEFT | wx.RIGHT | wx.BOTTOM, 12)

    dialog.SetSizerAndFit(root)
    apply_modal_ids(dialog, cancel_id=wx.ID_CANCEL, escape_id=wx.ID_CANCEL)
    field.SetFocus()
    field.SetInsertionPoint(0)
    if on_ready is not None:
        on_ready(field)
    try:
        show_modal(dialog, title)
    finally:
        dialog.Destroy()


def show_app_about(host: Any, body: str, *, app: str, app_name: str) -> None:
    """:func:`show_about_dialog` for an app-shell frame (``AppShellFrame``)."""
    show_about_dialog(
        host._dialog_parent(),
        app=app,
        app_name=app_name,
        body=body,
        announce=host._announce,
        show_modal=host._show_modal_dialog,
    )
