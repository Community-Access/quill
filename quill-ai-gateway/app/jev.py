"""Jev for the Command Key: ``POST /v1/decide`` (QUILL's docs/design/command-key.md 7.6 to 7.9).

Say or Type a Command asks Jev, TypeSafe's decision model, to pick one of this
window's commands when the matcher on the person's computer is not sure. This
service holds the TypeSafe key, so it never ships in an app, and it caps use so
the bill has a ceiling.

**A caller cannot ask its own questions.** The client sends only the app, the
catalogue version, the ordered ids of the commands it can run right now, and the
small state the request builder makes (the words typed, the surface name, recent
command ids, the last "Did you mean" offer, a number or duration the computer
found). The questions and every command description come from this service's
own copy of that catalogue version (``app/jev_catalogue/<version>.json``,
generated by ``python -m quill.tools.build_jev_gateway_catalogue --write`` in
QUILL), so an id this service does not know is refused, and the route cannot be
used to put anything else in front of TypeSafe. The question builder below is a
copy of ``quill/core/command_catalogue/jev_request.py``'s, kept identical by
``tests/test_decide.py``, so the own-key route and this route ask the same
questions.

**Caps (7.7),** all from the environment, so changing one needs a restart and no
new build: per device a minute, per address a minute, everyone a day, and a
dollar ceiling a month. Over any of them the answer is ``limit_reached``; the app
says one line once and stops asking until the next day.

**Nothing a person typed is logged or stored.** Only aggregate counts are kept,
in Redis, per day: requests, answers, failures, refusals by reason, input tokens
and total latency.
"""

from __future__ import annotations

import json
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from functools import lru_cache
from pathlib import Path
from typing import Any

import requests

#: The pinned model; a new version runs QUILL's recorded live suite before this moves.
JEV_MODEL = "jev-1.14.0"
#: TypeSafe's price for jev-1.14.0: $0.042 per million input tokens; output is free.
USD_PER_INPUT_TOKEN = 0.042 / 1_000_000
MAX_CANDIDATES = 60
MAX_REQUEST_CHARS = 300
MAX_SURFACE_CHARS = 80
NONE_OF_THESE = "none"
_RECENT = 5
_CATALOGUE_DIR = Path(__file__).resolve().parent / "jev_catalogue"


class DecideError(Exception):
    """A refusal or failure, with the HTTP status and the ``error`` word the client reads."""

    def __init__(self, status: int, error: str, message: str) -> None:
        super().__init__(message)
        self.status = status
        self.error = error
        self.message = message


@lru_cache(maxsize=1)
def _catalogues() -> dict[str, dict[str, dict[str, dict[str, Any]]]]:
    """Every catalogue version this service ships, read once, keyed by version.

    The caller's version is only ever looked up in this table, never turned
    into a file name, so nothing a caller sends can reach the file system.
    """
    found: dict[str, dict[str, dict[str, dict[str, Any]]]] = {}
    for path in sorted(_CATALOGUE_DIR.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        found[str(data["version"])] = data["apps"]
    return found


def catalogue(version: object) -> dict[str, dict[str, dict[str, Any]]] | None:
    """The command descriptions for *version*, by app and id, or None for an unknown version."""
    return _catalogues().get(version) if isinstance(version, str) else None


def _clean_text(value: object, limit: int) -> str:
    return value[:limit] if isinstance(value, str) else ""


def clean_state(raw: object, app: str, known: set[str]) -> dict[str, Any]:
    """The state, rebuilt field by field from what the request builder sends.

    Anything else in what arrived is dropped, never forwarded: this is what
    stops the route carrying more than the person agreed to send.
    """
    raw = raw if isinstance(raw, dict) else {}
    request_text = _clean_text(raw.get("request"), MAX_REQUEST_CHARS).strip()
    if not request_text:
        raise DecideError(400, "bad_request", "The request had no words.")
    recent_raw = raw.get("recent") if isinstance(raw.get("recent"), list) else []
    recent = [
        {"id": item["id"]}
        for item in recent_raw
        if isinstance(item, dict) and item.get("id") in known
    ][-_RECENT:]
    offer_raw = raw.get("last_offer") if isinstance(raw.get("last_offer"), list) else []
    last_offer = [item for item in offer_raw if isinstance(item, str) and item in known][
        :MAX_CANDIDATES
    ]
    matches = raw.get("local_matches") if isinstance(raw.get("local_matches"), dict) else {}

    def number(value: object) -> float | int | None:
        if isinstance(value, bool) or not isinstance(value, int | float):
            return None
        return value

    state: dict[str, Any] = {
        "request": request_text,
        "app": app,
        "surface": _clean_text(raw.get("surface"), MAX_SURFACE_CHARS),
        "recent": recent,
        "last_offer": last_offer,
        "local_matches": {
            "number": number(matches.get("number")),
            "duration_seconds": number(matches.get("duration_seconds")),
        },
    }
    heard = raw.get("heard_alternatives")
    if isinstance(heard, list):
        alternatives = [item[:MAX_REQUEST_CHARS] for item in heard[:2] if isinstance(item, str)]
        if alternatives:
            state["heard_alternatives"] = alternatives
    return state


def build_questions(
    rows: dict[str, dict[str, Any]], ids: list[str], with_correction: bool
) -> dict[str, Any]:
    """The same questions QUILL's ``jev_request._questions`` builds, from this service's rows."""
    criteria = {command_id: rows[command_id]["criterion"] for command_id in ids}
    criteria[NONE_OF_THESE] = "None of these: the request asks for something else."
    questions: dict[str, Any] = {
        "fits": {
            "type": "noul",
            "instructions": (
                "The request asks this app to do one of the listed actions, or asks what it can do."
            ),
        },
        "action": {
            "type": "choice",
            "instructions": "Which action does the request ask for?",
            "criteria": criteria,
        },
        "is_question": {
            "type": "noul",
            "instructions": "The request asks for information, not an action.",
        },
    }
    if any(rows[command_id].get("stepped") for command_id in ids):
        questions["size"] = {
            "type": "choice",
            "instructions": "If the action is a step, how big a step does the request want?",
            "criteria": {"small": "A little, or one step.", "large": "A lot, or several steps."},
        }
    if with_correction:
        questions["correction"] = {
            "type": "noul",
            "instructions": "The request corrects or rejects the previous result.",
        }
    return questions


@dataclass(frozen=True)
class Built:
    body: dict[str, Any]
    offered: tuple[str, ...]


def build_body(payload: object) -> Built:
    """The TypeSafe request for a ``/v1/decide`` body, or a 400 saying what was wrong."""
    payload = payload if isinstance(payload, dict) else {}
    apps = catalogue(payload.get("catalogue_version"))
    if apps is None:
        raise DecideError(400, "unknown_catalogue", "This version of QUILL is not known here yet.")
    app = payload.get("app")
    if not isinstance(app, str) or app not in apps:
        raise DecideError(400, "unknown_app", "That app is not known here.")
    rows = apps[app]
    ids = payload.get("candidates")
    if (
        not isinstance(ids, list)
        or not ids
        or len(ids) > MAX_CANDIDATES
        or not all(isinstance(item, str) for item in ids)
        or len(set(ids)) != len(ids)
    ):
        raise DecideError(400, "bad_candidates", "The list of commands was not usable.")
    unknown = [item for item in ids if item not in rows]
    if unknown:
        raise DecideError(400, "unknown_command", "A command in the list is not known here.")
    state = clean_state(payload.get("state"), app, set(rows))
    questions = build_questions(rows, ids, bool(state["recent"] or state["last_offer"]))
    return Built(
        body={"model": JEV_MODEL, "state": state, "questions": questions}, offered=tuple(ids)
    )


# -- caps and counts -------------------------------------------------------------


def _now() -> datetime:
    return datetime.now(UTC)


def _day(now: datetime) -> str:
    return now.strftime("%Y%m%d")


def _month(now: datetime) -> str:
    return now.strftime("%Y%m")


def _bump(redis_client, key: str, ttl: int, by: int = 1) -> int:
    value = int(redis_client.incrby(key, by))
    if value == by:
        redis_client.expire(key, ttl)
    return value


def count(redis_client, what: str, by: int = 1, now: datetime | None = None) -> None:
    """One aggregate counter for today. Never a body, never an id from the request."""
    try:
        _bump(redis_client, f"jev:stats:{_day(now or _now())}:{what}", 40 * 24 * 3600, by)
    except Exception:  # noqa: BLE001 - a lost count must never fail a request
        pass


def check_caps(config, redis_client, device_id: str, ip: str, now: datetime | None = None) -> None:
    """Every cap in 7.7, cheapest first. Raises ``limit_reached`` when one is over."""
    now = now or _now()
    minute = now.strftime("%Y%m%d%H%M")
    spent = float(redis_client.get(f"jev:usd:{_month(now)}") or 0.0)
    if spent >= float(config["JEV_MONTHLY_USD_CEILING"]):
        raise DecideError(429, "limit_reached", "Jev's monthly budget is spent.")
    checks = (
        (f"jev:dev:{device_id}:{minute}", 120, int(config["JEV_DEVICE_PER_MINUTE"])),
        (f"jev:ip:{ip}:{minute}", 120, int(config["JEV_IP_PER_MINUTE"])) if ip else None,
        (f"jev:day:{_day(now)}", 2 * 24 * 3600, int(config["JEV_DAILY_REQUEST_CAP"])),
    )
    for check in checks:
        if check is None:
            continue
        key, ttl, cap = check
        if _bump(redis_client, key, ttl) > cap:
            raise DecideError(429, "limit_reached", "Jev's limit is reached for now.")


def note_spend(redis_client, input_tokens: int, now: datetime | None = None) -> None:
    now = now or _now()
    try:
        key = f"jev:usd:{_month(now)}"
        redis_client.incrbyfloat(key, input_tokens * USD_PER_INPUT_TOKEN)
        redis_client.expire(key, 40 * 24 * 3600)
    except Exception:  # noqa: BLE001
        pass


# -- the one outbound call ---------------------------------------------------------


def ask_typesafe(config, body: dict[str, Any], offered: tuple[str, ...]) -> dict[str, Any]:
    """POST the body to TypeSafe with the service's key; return only the answer fields."""
    started = time.monotonic()
    try:
        response = requests.post(
            config["TYPESAFE_URL"],
            json=body,
            headers={
                "Authorization": f"Bearer {config['TYPESAFE_API_KEY']}",
                "Content-Type": "application/json",
                "Accept": "application/json",
                "User-Agent": "QUILL-AI-Gateway/1",
            },
            timeout=float(config["TYPESAFE_TIMEOUT_SECONDS"]),
        )
    except requests.Timeout:
        raise DecideError(504, "failed", "Jev took too long to answer.") from None
    except requests.RequestException:
        raise DecideError(502, "failed", "Jev could not be reached.") from None
    finally:
        elapsed_ms = int((time.monotonic() - started) * 1000)
    if response.status_code == 402:
        raise DecideError(402, "no_credit", "Jev's credit is spent for now.")
    if response.status_code in (401, 403):
        raise DecideError(503, "disabled", "Jev is not set up on this service.")
    if response.status_code != 200:
        raise DecideError(502, "failed", f"Jev answered with status {response.status_code}.")
    try:
        raw = response.json()
    except ValueError:
        raise DecideError(502, "failed", "Jev's answer was not JSON.") from None
    answers = raw.get("answers") if isinstance(raw, dict) else None
    action = answers.get("action") if isinstance(answers, dict) else None
    probabilities = action.get("probabilities") if isinstance(action, dict) else None
    if not isinstance(probabilities, dict) or not probabilities:
        raise DecideError(502, "failed", "Jev's answer had no choice.")
    allowed = set(offered) | {NONE_OF_THESE}
    if any(option not in allowed for option in probabilities):
        raise DecideError(502, "failed", "Jev answered with a command it was not offered.")
    usage = raw.get("usage") if isinstance(raw.get("usage"), dict) else {}
    tokens = usage.get("input_tokens", 0)
    return {
        "answers": answers,
        "model": str(raw.get("model", JEV_MODEL)),
        "usage": {"input_tokens": tokens if isinstance(tokens, int) else 0},
        "latency_ms": elapsed_ms,
    }
